#!/usr/bin/env python3
"""Compile skills/<name>/<file> into skills_data.mbt.

The binary carries every SKILL.md and script, so `serbox skills install`
works from a standalone download with no checkout and no network.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
OUT = ROOT / "skills_data.mbt"


def esc(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )


def main() -> int:
    if not SKILLS.is_dir():
        print(f"gen-skills: {SKILLS} is missing", file=sys.stderr)
        return 1
    groups = []
    for skill_dir in sorted(p for p in SKILLS.iterdir() if p.is_dir()):
        files = sorted(p for p in skill_dir.rglob("*") if p.is_file())
        if not any(p.name == "SKILL.md" for p in files):
            print(f"gen-skills: {skill_dir} has no SKILL.md", file=sys.stderr)
            return 1
        groups.append((skill_dir.name, files))
    if not groups:
        print("gen-skills: no skills found", file=sys.stderr)
        return 1

    lines = [
        "// Generated by scripts/gen-skills.py from skills/; do not edit.",
        "// Regenerate with `make skills` or `python3 scripts/gen-skills.py`.",
        "",
    ]
    for index, (name, files) in enumerate(groups):
        lines.append(f"let skill_group_{index} : Array[SkillFile] = [")
        for path in files:
            rel = path.relative_to(SKILLS / name).as_posix()
            body = path.read_text(encoding="utf-8")
            if "\x00" in body:
                print(f"gen-skills: NUL in {path}", file=sys.stderr)
                return 1
            lines.append(
                '  { skill: "%s", path: "%s", body: "%s" },'
                % (esc(name), esc(rel), esc(body))
            )
        lines.append("]")
        lines.append("")

    lines.append("///|")
    lines.append("pub fn bundled_skill_files() -> Array[SkillFile] {")
    lines.append("  let files : Array[SkillFile] = []")
    for index in range(len(groups)):
        lines.append(f"  for file in skill_group_{index} {{")
        lines.append("    files.push(file)")
        lines.append("  }")
    lines.append("  files")
    lines.append("}")
    lines.append("")

    text = "\n".join(lines)
    if OUT.exists() and OUT.read_text(encoding="utf-8") == text:
        print(f"gen-skills: {OUT.name} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"gen-skills: wrote {OUT.name} ({len(text)} bytes, {len(groups)} skills)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
